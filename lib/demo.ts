export function getDemoTranscript(id: string): Transcript {
  const match = /^demo-douyin-.*-([0-9])$/.exec(id);
  const text = match && demoVoiceovers[Number(match[1])];
  if (!text) return { status: "error", error: "未找到这条演示作品的语音文案。" };
  return { status: "done", rawText: text, warning: "演示语音文案，未调用语音服务。" };
}
